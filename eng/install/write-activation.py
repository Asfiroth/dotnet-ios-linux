#!/usr/bin/env python3
"""Write a shell activation file that preserves arbitrary installation paths."""

from __future__ import annotations

import argparse
import os
import shlex
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--data-root", type=Path, required=True)
    parser.add_argument("--dotnet-root", type=Path, required=True)
    parser.add_argument("--install-id", required=True)
    parser.add_argument("--project-version", required=True)
    args = parser.parse_args()

    output = args.output.expanduser().absolute()
    data_root = args.data_root.expanduser().absolute()
    dotnet_root = args.dotnet_root.expanduser().absolute()
    if not args.install_id or "/" in args.install_id or "\n" in args.install_id:
        raise SystemExit("activation writer: invalid install ID")

    swift = f"$DOTNET_IOS_LINUX_ROOT/toolchains/{args.install_id}/swift-6.4.0/usr/bin"
    lines = [
        f"# Generated by dotnet-ios-linux {args.project_version}. Source this file explicitly.",
        f"export DOTNET_IOS_LINUX_ROOT={shlex.quote(str(data_root))}",
        f"export DOTNET_ROOT={shlex.quote(str(dotnet_root))}",
        'export DEVELOPER_DIR="$DOTNET_IOS_LINUX_ROOT/Xcode.app/Contents/Developer"',
        f'export DOTNET_IOS_LINUX_CLANG="{swift}/clang"',
        f'export DOTNET_IOS_LINUX_CLANGXX="{swift}/clang++"',
        f'export PATH="$DOTNET_ROOT:$DOTNET_ROOT/tools:$DOTNET_IOS_LINUX_ROOT/bin:{swift}:$DEVELOPER_DIR/usr/bin:$PATH"',
        "",
    ]
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_name(output.name + f".tmp.{os.getpid()}")
    temporary.write_text("\n".join(lines), encoding="utf-8")
    os.replace(temporary, output)


if __name__ == "__main__":
    main()
